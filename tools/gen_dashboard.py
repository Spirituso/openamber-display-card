#!/usr/bin/env python3
"""Turn the tested dashboard (dashboard/openamber-display.yaml) into src/dashboard.js.

Every entity id of the author's installation is replaced by a slot token; each slot keeps the
Home Assistant domain and the entity name from the firmware, so the strategy can look up the
user's own entity ids at runtime.
Usage: python3 tools/gen_dashboard.py > src/dashboard.js
"""
import json, re, sys, unicodedata, pathlib, yaml

root = pathlib.Path(__file__).resolve().parent.parent
dash = yaml.safe_load((root / 'dashboard/openamber-display.yaml').read_text())
graph = (root / 'dashboard/oa-graph.js').read_text()
src = (root / 'src/entities.js').read_text()
ENT = {k: (d, n) for k, d, n in re.findall(r'^\s*([a-z0-9_]+): \["([a-z_]+)", "(.*)"\],?$', src, re.M)}

# Names that the slug match below cannot resolve (not in entities.js, or ambiguous).
OVERRIDE = {
    'number.zentrale_openamber_stooklijn_zone_2_10degc': 'Stooklijn zone 2 @ +10°C',
    'number.zentrale_openamber_stooklijn_zone_2_10degc_2': 'Stooklijn zone 2 @ -10°C',
    'select.zentrale_openamber_scherm_uit_na': 'Scherm uit na',
    'sensor.zentrale_openamber_eebus_ems': 'EEBUS EMS',
    'sensor.zentrale_openamber_free_psram': 'Free PSRAM',
    'sensor.zentrale_openamber_heap_fragmentation': 'Heap Fragmentation',
    'sensor.zentrale_openamber_heap_max_block': 'Heap Max Block',
    'sensor.zentrale_openamber_heap_free': 'Heap Free',
}
KEEP = {'input_select.openamber_display_taal'}  # helper created by the user, same id everywhere

def slug(s):
    s = s.replace('°', 'deg').replace('⁄', '_')
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '_', s).strip('_')

idx = {}
for k, (d, n) in ENT.items():
    idx.setdefault(slug(n), []).append(n)

ID_RE = re.compile(r'\b((?:sensor|binary_sensor|switch|number|select|button|climate|update|time|input_select)\.(?:zentrale_)?openamber_[a-z0-9_]+)')
text = json.dumps(dash, ensure_ascii=False)
ids = sorted(set(ID_RE.findall(text)) | set(ID_RE.findall(graph)))
slots, miss = {}, []
for e in ids:
    if e in KEEP:
        continue
    dom, obj = e.split('.', 1)
    if e in OVERRIDE:
        name = OVERRIDE[e]
    else:
        o = re.sub(r'^(zentrale_)?openamber_', '', obj)
        names = idx.get(o) or idx.get(re.sub(r'_2$', '', o))
        if not names or len(set(names)) > 1:
            miss.append(e); continue
        name = names[0]
    slots[e] = [dom, name]
if miss:
    sys.exit('unresolved: %s' % miss)
order = list(slots)
tok = {e: '@@%d@@' % i for i, e in enumerate(order)}
text = ID_RE.sub(lambda m: tok.get(m.group(1), m.group(1)), text)
print('// Generated by tools/gen_dashboard.py from dashboard/openamber-display.yaml. Do not edit by hand.')
print('export const SLOTS = %s;' % json.dumps([slots[e] + [e] for e in order], ensure_ascii=False))
print('export const DASHBOARD = %s;' % text)

# The Grafiek element, with its entity ids looked up through the map the strategy builds.
g = graph.replace("const E = {", "const E0 = {", 1).replace("const D = {", "const D0 = {", 1)
g = g.replace("const CL = '", "const CL0 = '", 1)
g = g.replace("const NS = ", "const M = (x) => (window.__oaMap && window.__oaMap[x]) || x;\n"
              "const E = new Proxy(E0, { get: (t, k) => M(t[k]) });\n"
              "const D = new Proxy(D0, { get: (t, k) => M(t[k]) });\n"
              "const NS = ", 1)
g = g.replace("[CL]", "[M(CL0)]")
assert "const CL =" not in g and "M(CL0)" in g
(root / 'src/graph.js').write_text('// Generated by tools/gen_dashboard.py from dashboard/oa-graph.js. Do not edit by hand.\n' + g)
