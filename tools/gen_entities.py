#!/usr/bin/env python3
"""Generate src/entities.js from an OpenAmber firmware checkout.

Usage: python3 tools/gen_entities.py /path/to/openamber > src/entities.js

Every ESPHome component with both an `id:` and a `name:` becomes one entry:
    <esphome id>: [<home assistant domain>, <entity name as set in the firmware>]
The card finds the matching Home Assistant entity through the entity registry
(unique_id ends with /<domain>/<name>), so it works whatever the user renamed
the device or the entities to.
"""
import json, os, re, sys

DOMAIN = {'text_sensor': 'sensor', 'datetime': 'time'}
SKIP_DIRS = ('mock', 'test', '/ui')

def scan(root):
    res = {}
    for base, _, files in os.walk(root):
        if any(s in base for s in SKIP_DIRS):
            continue
        for f in sorted(files):
            if not f.endswith('.yaml'):
                continue
            dom, item = None, None
            for line in open(os.path.join(base, f), encoding='utf-8-sig'):
                m = re.match(r'^([a-z_]+):\s*$', line)
                if m:
                    dom, item = m.group(1), None
                    continue
                m = re.match(r'^(\s*)- (platform|id|name):', line)
                if m and len(m.group(1)) <= 2:
                    item = {'dom': dom}
                m = re.match(r'^\s*-?\s*id:\s*([a-z0-9_]+)\s*$', line)
                if m and item is not None and 'id' not in item:
                    item['id'] = m.group(1)
                m = re.match(r'^\s*-?\s*name:\s*"?([^"#]+?)"?\s*$', line)
                if m and item is not None and 'name' not in item:
                    item['name'] = m.group(1)
                if item and 'id' in item and 'name' in item and item['dom']:
                    res[item['id']] = [DOMAIN.get(item['dom'], item['dom']), item['name']]
                    item = None
    return res

if __name__ == '__main__':
    root = sys.argv[1] if len(sys.argv) > 1 else '.'
    src = os.path.join(root, 'src', 'openamber') if os.path.isdir(os.path.join(root, 'src', 'openamber')) else root
    ents = scan(src)
    print('// Generated by tools/gen_entities.py from the OpenAmber firmware. Do not edit by hand.')
    print('export const ENTITIES = {')
    for k, v in sorted(ents.items()):
        print(f'  {k}: {json.dumps(v, ensure_ascii=False)},')
    print('};')
